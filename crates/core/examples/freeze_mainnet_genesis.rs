//! One-off tool used during the `audit/hardening-tui` mainnet-bootstrap
//! step. Loads `config/mainnet.toml`, retargets the genesis to a real
//! (non-trivial) difficulty, then grinds the genesis nonce until the
//! resulting header satisfies PoW.
//!
//! Run with:
//!   cargo run -p scam-core --example freeze_mainnet_genesis
//!
//! Prints the (genesis_target, genesis_nonce, genesis_message, genesis_timestamp,
//! computed_block_hash, computed_merkle_root) tuple as TOML snippets ready
//! to paste into `config/mainnet.toml`.

use std::time::{SystemTime, UNIX_EPOCH};

use scam_core::{ChainConfig, Target, block_meets_pow};
// Used solely for compile-time sanity that Target hex parses cleanly.

/// "00000fff..." = 20-bit difficulty (≈ 1M hash attempts on average).
/// Mild enough to grind in a few seconds at debug build speed, real
/// enough that a chain replay attacker can't trivially construct
/// alternate genesis blocks of equivalent work.
const FROZEN_TARGET_HEX: &str =
    "00000fffffffffffffffffffffffffffffffffffffffffffffffffffffffffff";

/// Visible commitment to the bootstrap context. Bitcoin's genesis
/// embedded a newspaper headline; we embed the audit branch + ISO date
/// so the genesis is timestamped against an external reference.
const FROZEN_MESSAGE: &str =
    "SCAM mainnet bootstrap @ audit/hardening-tui 2026-05-16";

fn main() {
    let mut cfg: ChainConfig = toml::from_str(include_str!("../../../config/mainnet.toml"))
        .expect("config/mainnet.toml must parse");

    cfg.genesis_target = FROZEN_TARGET_HEX.to_owned();
    cfg.genesis_message = FROZEN_MESSAGE.to_owned();
    // Fix timestamp at the same instant the freeze ran; this becomes
    // the genesis_timestamp baked into the lockfile.
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system time")
        .as_secs();
    cfg.genesis_timestamp = now;

    // (Target parsed for early sanity rejection only — the actual hash
    // check happens inside `block_meets_pow`.)
    let _target = Target::from_hex(FROZEN_TARGET_HEX).expect("valid target hex");

    // Grind nonces. Real Bitcoin genesis mining took ~2^32 attempts at
    // 0x1d00ffff (4M ms) and Satoshi just left it running. Our target
    // is ~20 bits so this terminates in seconds.
    let mut nonce: u64 = 0;
    loop {
        cfg.genesis_nonce = nonce;
        let block = cfg.build_genesis_block().expect("genesis builds");

        if block_meets_pow(&block) {
            println!("# audit/hardening-tui mainnet genesis freeze");
            println!("# generated by crates/core/examples/freeze_mainnet_genesis.rs");
            println!("genesis_message    = \"{FROZEN_MESSAGE}\"");
            println!("genesis_timestamp  = {now}");
            println!("genesis_target     = \"{FROZEN_TARGET_HEX}\"");
            println!("genesis_nonce      = {nonce}");
            println!("# resulting hashes (compute-only, not pasted into toml):");
            println!("# block_hash    = {}", block.header.block_hash().to_hex());
            println!("# merkle_root   = {}", block.header.merkle_root.to_hex());
            println!("# target_check  = ok (hash <= target)");
            println!("# tried_nonces  = {nonce}");
            return;
        }
        nonce = nonce.checked_add(1).expect("nonce overflow before solving");
        if nonce % 1_000_000 == 0 {
            eprintln!("...still grinding, nonce = {nonce}");
        }
        // Sanity ceiling: a 20-bit target should solve well before u32::MAX.
        if nonce > 1u64 << 30 {
            panic!(
                "target {FROZEN_TARGET_HEX} not solved after 2^30 nonces — check target"
            );
        }
    }
    // unreachable (loop always returns or panics).
}
